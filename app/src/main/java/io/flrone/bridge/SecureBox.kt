/**
 * The credential envelope for values that must not rest as plaintext (alignment item S10).
 *
 * The WebDAV account lives in the `preferences` JSON document, which is a plain file in the app's
 * private storage. Its password used to sit there in the clear. This box seals it with an
 * AES/GCM key that never leaves the Android Keystore, and hands the token back as
 * `enc:v1:<base64(nonce||ciphertext)>`. The Dart side (`services/webdav_account.dart`) decides
 * *which* values to seal; the host only performs the primitive.
 *
 * Why a Keystore key rather than a derived one: the key material is generated inside the TEE and
 * is not readable even from a rooted device without a full key extraction, whereas a value derived
 * from an app constant is one `strings` away from the same plaintext. The trade-off is that the
 * ciphertext is device-bound — see [open]'s contract for what a reset key means.
 *
 * Layout: the envelope is versioned in the prefix, the nonce is the first [EnvelopeCodec.NONCE_BYTES]
 * bytes (GCM's required 96 bits) and the rest is the ciphertext including the 128-bit tag. Nothing
 * about the plaintext, the key or the device is stored outside the token.
 *
 * Testability: [EnvelopeCodec] and [AesGcm] are plain JVM (only `javax.crypto`), and [parseSecureCall]
 * is the channel's argument contract. `SecureBoxTest` drives those three; the Keystore adapter below
 * (`AndroidKeyStore`) and [SecureChannel] are device-only and covered by the in-app path.
 */
internal object EnvelopeCodec {

    /** The only version this build understands; an unknown prefix is a malformed token, not a guess. */
    const val PREFIX = "enc:v1:"

    /** AES/GCM's recommended nonce length. */
    const val NONCE_BYTES = 12

    /** The GCM tag length the adapter requests on both ends. */
    const val TAG_BYTES = 16

    /** True when [value] already carries this build's envelope (the Dart guard's mirror). */
    fun isSealed(value: String): Boolean = value.startsWith(PREFIX)

    /** The stored form of one sealed value. */
    fun encode(nonce: ByteArray, ciphertext: ByteArray): String =
        PREFIX + base64Encode(nonce + ciphertext)

    /**
     * Splits a token back into its nonce and ciphertext. Null for anything this build did not
     * write: a different prefix (`enc:v2:` from a future build, a plaintext password), a body that
     * is not base64, or one too short to hold a nonce and a tag. Never throws.
     */
    fun decode(token: String): Pair<ByteArray, ByteArray>? {
        if (!isSealed(token)) return null
        val body = base64Decode(token.substring(PREFIX.length)) ?: return null
        if (body.size < NONCE_BYTES + TAG_BYTES) return null
        return body.copyOfRange(0, NONCE_BYTES) to body.copyOfRange(NONCE_BYTES, body.size)
    }
}

/**
 * The AES/GCM halves over an arbitrary [SecretKey], so a JVM test can drive them with a plain
 * in-memory key. The Android adapter supplies the Keystore one ([SecureBox.key]).
 */
internal object AesGcm {

    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val TAG_BITS = EnvelopeCodec.TAG_BYTES * 8

    /**
     * Seals [plaintext] with a fresh random nonce. The IV is generated by the cipher (the Keystore
     * key sets `setRandomizedEncryptionRequired(true)`, which refuses a caller-supplied one) and is
     * read back from [Cipher.getIV] into the envelope.
     */
    fun seal(key: SecretKey, plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        return EnvelopeCodec.encode(cipher.iv, ciphertext)
    }

    /**
     * Opens [token]; null when it is not an envelope this build wrote, when the key is not the one
     * that sealed it, or when the tag does not verify (a tampered or truncated body is an answer,
     * not an exception — a Keystore reset and a hand-edited document both look like this).
     */
    fun open(key: SecretKey, token: String): String? {
        val (nonce, ciphertext) = EnvelopeCodec.decode(token) ?: return null
        return runCatching {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, nonce))
            String(cipher.doFinal(ciphertext), Charsets.UTF_8)
        }.getOrNull()
    }
}

/**
 * The Android Keystore adapter. The key is generated on first `seal` inside `AndroidKeyStore`
 * (alias [KEY_ALIAS], AES-256, GCM, randomised IV, no user authentication), so the plaintext can be
 * recovered only by this app on this device's unlocked keystore.
 *
 * A key that is gone — an app reinstall clears the Keystore entry, and so does a lock-screen
 * credential reset on some OEMs — makes every stored envelope undecryptable. [open] then answers
 * null and the Dart caller reports "enter the password again"; it never throws into the channel and
 * it deliberately does **not** mint a replacement key, because a fresh key would silently orphan the
 * ciphertext still in the document.
 */
internal object SecureBox {

    /** The `io.flrone/secure` MethodChannel this box answers on. */
    const val CHANNEL = "io.flrone/secure"

    private const val KEYSTORE = "AndroidKeyStore"
    private const val KEY_ALIAS = "flrone.credentials"

    /** Serialises key creation: two concurrent `seal`s must not race `generateKey`. */
    private val lock = Any()

    fun seal(plaintext: String): String = AesGcm.seal(key(), plaintext)

    fun open(token: String): String? = AesGcm.open(existingKey() ?: return null, token)

    /** The key, created on first use. A Keystore that cannot create one throws, and the channel
     *  answers `seal_failed` rather than storing anything unsealed. */
    private fun key(): SecretKey = synchronized(lock) { stored() ?: generate() }

    /** The key if one exists: a read never mints one (see the class doc). */
    private fun existingKey(): SecretKey? = synchronized(lock) { stored() }

    private fun stored(): SecretKey? =
        KeyStore.getInstance(KEYSTORE).apply { load(null) }
            .let { (it.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.secretKey }

    private fun generate(): SecretKey =
        KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE).run {
            init(
                KeyGenParameterSpec.Builder(
                    KEY_ALIAS,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setKeySize(256)
                    // Not user-auth-required: backups run from a background that no keyguard prompt
                    // can appear in. Randomised IV stays on so the nonce is the cipher's, never ours.
                    .setRandomizedEncryptionRequired(true)
                    .setUserAuthenticationRequired(false)
                    .build(),
            )
            generateKey()
        }
}

/**
 * The channel's argument contract, free of `MethodCall` so a JVM test can drive it: the payload is
 * always `{value: String}` and the method is one of [Seal]/[Open]/[Unknown].
 */
internal sealed interface SecureCall {
    data class Seal(val value: String) : SecureCall
    data class Open(val value: String) : SecureCall
    object Unknown : SecureCall
    data class Invalid(val reason: String) : SecureCall
}

/**
 * Reads one `seal`/`open` call. An absent or non-string `value` — and an empty `seal` — is
 * [SecureCall.Invalid] (a seal of nothing is a caller bug, and echoing it would look like a stored
 * secret); any other method is [SecureCall.Unknown] and becomes `notImplemented`. `open` accepts any
 * string: a malformed token is its ordinary null answer, not an argument error.
 */
internal fun parseSecureCall(method: String, arguments: Any?): SecureCall {
    if (method != "seal" && method != "open") return SecureCall.Unknown
    val value = (arguments as? Map<*, *>)?.get("value") as? String
        ?: return SecureCall.Invalid("the argument `value` must be a string")
    if (method == "seal" && value.isEmpty()) return SecureCall.Invalid("there is nothing to seal")
    return if (method == "seal") SecureCall.Seal(value) else SecureCall.Open(value)
}

/**
 * The `io.flrone/secure` channel: `seal(value) -> String` and `open(value) -> String?`.
 *
 * Registered next to [io.flrone.flutter.FlronePlatformBridge] rather than inside it: the credentials box
 * is a separate contract with its own budget entry (`tools/diagnostics/aar_channels.txt`), and the
 * bridge is already large enough. The work runs on one background thread — a Keystore `init` plus
 * decrypt measured milliseconds, which is not something to spend inside a frame — and every reply
 * is posted back to the main looper, where Flutter's `MethodChannel.Result` belongs.
 *
 * Nothing here logs: not the plaintext, not the token, not the key. The failure texts name the
 * operation only.
 */
internal class SecureChannel(messenger: BinaryMessenger) : MethodChannel.MethodCallHandler {

    private val channel = MethodChannel(messenger, SecureBox.CHANNEL)

    /** One worker, so two seals cannot interleave their Keystore key generation. */
    private val worker = Executors.newSingleThreadExecutor { runnable ->
        Thread(runnable, "flrone-secure")
    }

    private val main = Handler(Looper.getMainLooper())

    fun attach() {
        channel.setMethodCallHandler(this)
    }

    fun close() {
        channel.setMethodCallHandler(null)
        worker.shutdownNow()
    }

    override fun onMethodCall(call: MethodCall, result: MethodChannel.Result) {
        when (val parsed = parseSecureCall(call.method, call.arguments)) {
            is SecureCall.Unknown -> result.notImplemented()
            is SecureCall.Invalid -> result.error("invalid_arguments", parsed.reason, null)
            is SecureCall.Seal -> worker.execute { deliver(result, "seal_failed") { SecureBox.seal(parsed.value) } }
            // A crypto failure is [AesGcm.open]'s documented null ("this device cannot open
            // it"); only an unexpected throw becomes a channel error, and it carries no value.
            is SecureCall.Open -> worker.execute { deliver(result, "open_failed") { SecureBox.open(parsed.value) } }
        }
    }

    /**
     * Runs [work] off the main thread and settles [result] on it. A failure answers `*_failed`
     * with the exception's class name only: a crypto exception's message can quote the input, and
     * the class is diagnosis enough.
     */
    private fun <T> deliver(result: MethodChannel.Result, code: String, work: () -> T) {
        val reply = runCatching(work)
        main.post {
            reply.fold(
                onSuccess = { result.success(it) },
                onFailure = { failure -> result.error(code, failure.javaClass.simpleName, null) },
            )
        }
    }
}

/** The base64 alphabet, RFC 4648 §4. */
private const val ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

/**
 * Standard base64 with `=` padding, written out rather than taken from a library:
 * `java.util.Base64` needs API 26 (the app's floor is 24) and `android.util.Base64` throws in a
 * JVM test. This is encoding only — the cryptography is `javax.crypto` — and `SecureBoxTest` pins
 * it against the RFC 4648 vectors and round trips.
 */
internal fun base64Encode(bytes: ByteArray): String {
    val text = StringBuilder((bytes.size + 2) / 3 * 4)
    var index = 0
    while (index + 2 < bytes.size) {
        val word = ((bytes[index].toInt() and 0xFF) shl 16) or
            ((bytes[index + 1].toInt() and 0xFF) shl 8) or
            (bytes[index + 2].toInt() and 0xFF)
        text.append(ALPHABET[(word shr 18) and 63])
            .append(ALPHABET[(word shr 12) and 63])
            .append(ALPHABET[(word shr 6) and 63])
            .append(ALPHABET[word and 63])
        index += 3
    }
    when (bytes.size - index) {
        1 -> {
            val word = (bytes[index].toInt() and 0xFF) shl 16
            text.append(ALPHABET[(word shr 18) and 63])
                .append(ALPHABET[(word shr 12) and 63])
                .append("==")
        }
        2 -> {
            val word = ((bytes[index].toInt() and 0xFF) shl 16) or
                ((bytes[index + 1].toInt() and 0xFF) shl 8)
            text.append(ALPHABET[(word shr 18) and 63])
                .append(ALPHABET[(word shr 12) and 63])
                .append(ALPHABET[(word shr 6) and 63])
                .append('=')
        }
    }
    return text.toString()
}

/**
 * The inverse of [base64Encode]; null for anything that is not one whole, correctly padded quantum
 * sequence. Padding is accepted only in the final quantum, which is what makes `decode`'s length
 * check meaningful for the envelope.
 */
internal fun base64Decode(text: String): ByteArray? {
    if (text.length % 4 != 0) return null
    if (text.isEmpty()) return ByteArray(0)
    val out = ByteArray(text.length / 4 * 3)
    var size = 0
    var index = 0
    while (index < text.length) {
        val last = index + 4 == text.length
        val c0 = alphabetIndex(text[index])
        val c1 = alphabetIndex(text[index + 1])
        if (c0 < 0 || c1 < 0) return null
        val third = text[index + 2]
        val fourth = text[index + 3]
        val c2: Int
        val c3: Int
        var produced: Int
        when {
            third == '=' -> {
                if (!last || fourth != '=') return null
                c2 = 0
                c3 = 0
                produced = 1
            }
            fourth == '=' -> {
                if (!last) return null
                c2 = alphabetIndex(third)
                if (c2 < 0) return null
                c3 = 0
                produced = 2
            }
            else -> {
                c2 = alphabetIndex(third)
                c3 = alphabetIndex(fourth)
                if (c2 < 0 || c3 < 0) return null
                produced = 3
            }
        }
        val word = (c0 shl 18) or (c1 shl 12) or (c2 shl 6) or c3
        out[size++] = (word shr 16).toByte()
        if (produced > 1) out[size++] = (word shr 8).toByte()
        if (produced > 2) out[size++] = word.toByte()
        index += 4
    }
    return out.copyOf(size)
}

private fun alphabetIndex(char: Char): Int = when (char) {
    in 'A'..'Z' -> char - 'A'
    in 'a'..'z' -> char - 'a' + 26
    in '0'..'9' -> char - '0' + 52
    '+' -> 62
    '/' -> 63
    else -> -1
}
