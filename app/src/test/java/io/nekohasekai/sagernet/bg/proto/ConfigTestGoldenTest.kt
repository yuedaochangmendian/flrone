package io.nekohasekai.sagernet.bg.proto

import io.flrone.bridge.DartProfileStore
import io.nekohasekai.sagernet.database.SettingsJsonStore
import io.nekohasekai.sagernet.outbound.config.GeneratedConfig
import org.json.JSONObject
import org.junit.After
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Before
import org.junit.Test
import java.io.File
import java.nio.file.Files
import java.security.MessageDigest
import java.util.Locale

/**
 * Stage 6 of the config.build migration: a golden harness for the **test config** (`buildTest`, generate.cpp
 * BuildTestConfig), driven through the production seam [CoreConfigs.buildTest] rather than the generator directly,
 * so the group lookup (landing / front proxy + group name) and the settings mapping are pinned with the output.
 *
 * Each case lives under `app/src/test/resources/config-test-golden/<case>/` and contains the documents a real
 * test session reads plus the call and the oracle output:
 *
 *  - `profiles.json`   — the Dart-owned profile document ([DartProfileStore] format). A candidate's `gid` names the
 *                        group whose `landing_proxy_id` / `front_proxy_id` the candidate carries; a referenced group
 *                        must have a **non-blank name**, because [CoreConfigs.buildTest] reads it through
 *                        `ProxyGroup.displayName()`, whose blank-name fallback needs Android resources the plain JVM
 *                        oracle has no Context for.
 *  - `settings.json`   — the Kotlin-owned settings document ([SettingsJsonStore] format).
 *                        `inbound_socks_port` must be present (DataStore would ask Binder for the per-user port
 *                        offset otherwise), `core_box_api_secret` must be non-empty (it is generated randomly when
 *                        blank) and `dns_query_timeout` must be a valid non-empty duration (the empty-duration error
 *                        text needs Android resources).
 *  - `build_test.json` — the call: `profileIds` (the candidates, in order; each a positive id, no repeats) and an
 *                        optional `goStage` marker reserving the case for a later Go builder stage.
 *  - `expected.json`   — **generated by this test, never hand-written**: the exact oracle envelope (coreConfig plus
 *                        SHA-256, ordered outbound tags / buckets, tun CIDR, involved ids and error).
 *
 * There is no `global_route_rules.json`: a test build reads no routing profile (no `proxy` tag, no rule-sets, no
 * inbound section). To add a case, copy a directory, edit the input documents, then run
 * `python tools/diagnostics/config_golden.py --suite test --update --case <case>` (or the whole set) and commit the
 * regenerated `expected.json`. The normal test run never rewrites expectations; it fails on any byte difference and
 * leaves the actual output in `app/build/config-test-golden/<case>/`.
 */
class ConfigTestGoldenTest {

    private var previousProfileDir: File? = null
    private var previousProfileLogger: (String, Throwable?) -> Unit = { _, _ -> }
    private var previousSettingsDir: File? = null
    private var previousSettingsLogger: (String, Throwable?) -> Unit = { _, _ -> }

    @Before
    fun setUp() {
        previousProfileDir = DartProfileStore.directory
        previousProfileLogger = DartProfileStore.logger
        previousSettingsDir = SettingsJsonStore.directory
        previousSettingsLogger = SettingsJsonStore.logger
        DartProfileStore.logger = { _, _ -> }
        SettingsJsonStore.logger = { _, _ -> }
    }

    @After
    fun tearDown() {
        DartProfileStore.directory = previousProfileDir
        DartProfileStore.logger = previousProfileLogger
        SettingsJsonStore.directory = previousSettingsDir
        SettingsJsonStore.logger = previousSettingsLogger
        DartProfileStore.invalidate()
    }

    @Test
    fun `test golden fixtures match the production buildTest envelope`() {
        val root = fixtureRoot()
        val cases = root.listFiles { file -> file.isDirectory }?.sortedBy { it.name }.orEmpty()
        assertTrue("no config-test-golden fixtures under ${root.absolutePath}", cases.isNotEmpty())

        val update = System.getProperty(ConfigTestGoldenPaths.UPDATE_PROPERTY) == "true"
        val failures = ArrayList<String>()
        for (caseDir in cases) {
            val caseName = caseDir.name
            val actual = try {
                generate(caseDir)
            } catch (error: Throwable) {
                failures.add("$caseName: buildTest oracle threw ${error::class.java.simpleName}: ${error.message}\n${error.stackTraceToString()}")
                continue
            }
            writeActual(caseName, actual)

            if (update) {
                println("config-test-golden: wrote actual for $caseName")
                continue
            }

            val expectedFile = File(caseDir, EXPECTED)
            if (!expectedFile.isFile) {
                failures.add("$caseName: expected.json is missing; run config_golden.py --suite test --update --case $caseName")
                continue
            }
            val expected = expectedFile.readText(Charsets.UTF_8)
            val provenance = try {
                JSONObject(expected)
            } catch (error: Exception) {
                failures.add("$caseName: expected.json is not valid JSON: ${error.message}")
                continue
            }
            if (provenance.optString("generatedBy") != GENERATED_BY) {
                failures.add("$caseName: expected.json was not produced by $GENERATED_BY")
                continue
            }
            val expectedSha = provenance.optString("sha256")
            if (expectedSha != sha256(provenance.optString("coreConfig"))) {
                failures.add("$caseName: expected.json sha256 does not match its coreConfig (edited by hand?)")
                continue
            }
            if (expected != actual) {
                failures.add("$caseName: ${describeFirstDifference(expected, actual)}")
            }
        }
        if (failures.isNotEmpty()) {
            fail(failures.joinToString("\n\n"))
        }
    }

    /**
     * The production chain for one fixture: documents -> [CoreConfigs.buildTest]. The store directories are the
     * per-case temp copies, exactly as a running service would see them.
     */
    private fun generate(caseDir: File): String {
        val buildTest = JSONObject(File(caseDir, BUILD).readText(Charsets.UTF_8))
        val ids = buildTest.optJSONArray("profileIds")
            ?: error("build_test.json needs a profileIds array")
        val profileIds = ArrayList<Long>(ids.length())
        for (index in 0 until ids.length()) {
            val id = ids.optLong(index, -1L)
            assertTrue(
                "${caseDir.name}: build_test.json profileIds[$index] must be a positive profile id, not $id",
                id > 0L,
            )
            profileIds.add(id)
        }
        assertTrue(
            "${caseDir.name}: build_test.json profileIds must not repeat an id " +
                "(buildTest collapses repeats silently, so the fixture would not test what it looks like)",
            profileIds.toSet().size == profileIds.size,
        )

        val work = Files.createTempDirectory("config-test-golden-${caseDir.name}-").toFile()
        try {
            for (name in INPUT_FILES) {
                val source = File(caseDir, name)
                assertTrue("$name is missing in fixture ${caseDir.name}", source.isFile)
                source.copyTo(File(work, name), overwrite = true)
            }
            DartProfileStore.directory = work
            DartProfileStore.invalidate()
            SettingsJsonStore.directory = work

            // SettingsMapper generates a random core_box_api_secret when the row is missing/blank;
            // a golden fixture must pin it or every run produces a different config.
            assertTrue(
                "${caseDir.name}: settings.json must set a non-empty core_box_api_secret " +
                    "(otherwise each build generates a random one)",
                !SettingsJsonStore.get("core_box_api_secret").isNullOrEmpty(),
            )
            val clashPort = SettingsJsonStore.get("core_box_clash_api")?.trim()?.toIntOrNull() ?: 0
            if (clashPort > 0) {
                assertTrue(
                    "${caseDir.name}: settings.json enables the Clash API and must set core_box_clash_api_secret",
                    !SettingsJsonStore.get("core_box_clash_api_secret").isNullOrEmpty(),
                )
            }
            // ConfigGenerator.validDuration("") builds its error text from Android resources, which a
            // plain JVM test has no Context for: fixtures must use a syntactically valid non-empty value.
            assertTrue(
                "${caseDir.name}: settings.json must set a non-empty dns_query_timeout (e.g. \"5s\"); " +
                    "the JVM oracle cannot render Validation's Android string for an empty duration",
                !SettingsJsonStore.get("dns_query_timeout").isNullOrEmpty(),
            )
            if (SettingsJsonStore.get("dns_optimistic") == "true") {
                assertTrue(
                    "${caseDir.name}: dns_optimistic requires a non-empty dns_optimistic_timeout for the JVM oracle",
                    !SettingsJsonStore.get("dns_optimistic_timeout").isNullOrEmpty(),
                )
            }

            return envelope(CoreConfigs.buildTest(profileIds))
        } finally {
            DartProfileStore.directory = null
            SettingsJsonStore.directory = null
            work.deleteRecursively()
        }
    }

    /** This test's own output directory; `config_golden.py` reads it and is the only writer of expected.json. */
    private fun writeActual(caseName: String, document: String) {
        val dir = File(ConfigTestGoldenPaths.outputRoot(), caseName).apply { mkdirs() }
        File(dir, "actual.json").writeText(document, Charsets.UTF_8)
    }

    /**
     * The deterministic envelope. Hand-written on purpose: org.json objects do not keep insertion order, and the
     * ordered arrays (tags, buckets) are part of the contract this harness pins.
     */
    private fun envelope(generated: GeneratedConfig): String = buildString {
        // The production map is insertion-ordered; walking outboundTags keeps the two arrays aligned even if a
        // future seam hands back a map type without an order guarantee.
        val tags = generated.outboundTags.map { tag -> tag to generated.tagToProfileId.getValue(tag) }
        append("{\n")
        append("  \"version\": 1,\n")
        append("  \"generatedBy\": \"").append(GENERATED_BY).append("\",\n")
        append("  \"sha256\": \"").append(sha256(generated.coreConfig)).append("\",\n")
        append("  \"coreConfig\": ").append(quote(generated.coreConfig)).append(",\n")
        append("  \"outboundTags\": ").append(quoteList(generated.outboundTags)).append(",\n")
        append("  \"tagToProfileId\": ").append(recordList(tags.map { (tag, id) ->
            "{\"tag\": ${quote(tag)}, \"profileId\": $id}"
        })).append(",\n")
        append("  \"fullConfigs\": ").append(recordList(generated.fullConfigs.entries.map { (id, config) ->
            "{\"profileId\": $id, \"config\": ${quote(config)}, \"sha256\": \"${sha256(config)}\"}"
        })).append(",\n")
        append("  \"skipped\": ").append(recordList(generated.skipped.entries.map { (id, reason) ->
            "{\"profileId\": $id, \"reason\": ${quote(reason)}}"
        })).append(",\n")
        append("  \"tunIPv4Cidr\": ").append(generated.tunIPv4Cidr?.let(::quote) ?: "null").append(",\n")
        append("  \"involvedProfileIds\": ").append(generated.involvedProfileIds.sorted().joinToString(",", "[", "]"))
        append(",\n")
        append("  \"error\": ").append(generated.error?.let(::quote) ?: "null").append('\n')
        append("}\n")
    }

    private fun quoteList(items: List<String>): String =
        if (items.isEmpty()) "[]"
        else items.joinToString(",\n    ", prefix = "[\n    ", postfix = "\n  ]") { quote(it) }

    private fun recordList(items: List<String>): String =
        if (items.isEmpty()) "[]"
        else items.joinToString(",\n    ", prefix = "[\n    ", postfix = "\n  ]") { it }

    private fun fixtureRoot(): File {
        val url = javaClass.getResource("/config-test-golden")
            ?: error("missing test resources /config-test-golden")
        return File(url.toURI())
    }

    private fun describeFirstDifference(expected: String, actual: String): String {
        val left = expected.toByteArray(Charsets.UTF_8)
        val right = actual.toByteArray(Charsets.UTF_8)
        val shared = minOf(left.size, right.size)
        var offset = 0
        while (offset < shared && left[offset] == right[offset]) offset++
        val leftContext = String(
            left, maxOf(0, offset - 24), minOf(left.size, offset + 24) - maxOf(0, offset - 24), Charsets.UTF_8,
        )
        val rightContext = String(
            right, maxOf(0, offset - 24), minOf(right.size, offset + 24) - maxOf(0, offset - 24), Charsets.UTF_8,
        )
        return buildString {
            append("envelope differs at byte offset ").append(offset)
            append(" (expected ").append(left.size).append(" bytes, actual ").append(right.size).append(" bytes)\n")
            append("  expected[..]: ").append(leftContext.replace("\n", "\\n")).append('\n')
            append("  actual[..]:   ").append(rightContext.replace("\n", "\\n"))
        }
    }

    private companion object {
        const val EXPECTED = "expected.json"
        const val BUILD = "build_test.json"
        const val GENERATED_BY = "ConfigTestGoldenTest"
        val INPUT_FILES = listOf("profiles.json", "settings.json", BUILD)

        fun quote(text: String): String = JSONObject.quote(text)

        fun sha256(text: String): String =
            MessageDigest.getInstance("SHA-256").digest(text.toByteArray(Charsets.UTF_8))
                .joinToString("") { String.format(Locale.ROOT, "%02x", it) }
    }
}

/** Path resolution shared with tools/diagnostics/config_golden.py (the `test` suite). */
internal object ConfigTestGoldenPaths {
    const val UPDATE_PROPERTY = "config.test.golden.update"
    const val OUTPUT_PROPERTY = "config.test.golden.outputDir"

    /** Defaults to `app/build/config-test-golden` because Gradle runs unit tests from the app module. */
    fun outputRoot(): File =
        System.getProperty(OUTPUT_PROPERTY)?.takeIf { it.isNotBlank() }?.let(::File)
            ?: File("build/config-test-golden")
}