package io.nekohasekai.sagernet.outbound.config

import io.flrone.bridge.DartProfileStore
import io.flrone.bridge.FlroneMode
import io.nekohasekai.sagernet.database.RouteJsonStore
import io.nekohasekai.sagernet.database.RouteManager
import io.nekohasekai.sagernet.database.SettingsJsonStore
import io.nekohasekai.sagernet.database.SettingsMapper
import io.nekohasekai.sagernet.route.RuleSetCatalog
import org.json.JSONObject
import org.junit.After
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Before
import org.junit.Test
import java.io.File
import java.nio.file.Files
import java.security.MessageDigest
import java.util.Locale

/**
 * Stage 0 of the config.build migration: a golden harness that pins the **current Kotlin**
 * `ConfigGenerator.build()` output byte for byte, so a future Go builder can be proven identical.
 *
 * Each case lives under `app/src/test/resources/config-golden/<case>/` and contains the four
 * documents a production build reads plus the oracle output:
 *
 *  - `profiles.json`          — the Dart-owned profile document ([DartProfileStore] format).
 *  - `settings.json`          — the Kotlin-owned settings document ([SettingsJsonStore] format).
 *                               `inbound_socks_port` must be present: without it DataStore asks
 *                               `Binder.getCallingUserHandle()` for the per-user port offset, which a
 *                               plain JVM unit test cannot answer. `core_box_api_secret` must be
 *                               non-empty (else it is generated randomly per run) and
 *                               `dns_query_timeout` must be a valid non-empty duration (the
 *                               empty-duration error text needs Android resources, absent in a
 *                               plain JVM test).
 *  - `global_route_rules.json`— the Go-owned global rule table ([RouteJsonStore] format).
 *  - `build.json`             — the build call: `selectedProfileId`, optional `deferRuleSets`,
 *                               optional `mode` ("vpn" | "proxy", overriding the document's
 *                               `serviceMode` for this case), optional `outboundMode`
 *                               ("rule" | "global" | "direct", the FlroneMode rewrite the
 *                               production routingInput applies), optional `landingProxyId` /
 *                               `frontProxyId` / `groupName`, optional `clockUnixSeconds` (a
 *                               fixed clock for auto-selector freshness and warm ages) and
 *                               optional `expectError` (the build must fail with the pinned text).
 *  - `expected.json`          — **generated by this test, never hand-written**: the exact
 *                               `coreConfig` string plus its SHA-256; an `expectError` case
 *                               pins `error` as well and leaves `coreConfig` empty.
 *
 * To add a case, copy a directory, edit the four input documents, then run
 * `python tools/diagnostics/config_golden.py --update --case <case>` (or the whole set) and
 * commit the regenerated `expected.json`. The normal test run never rewrites expectations; it
 * fails on any byte difference and leaves the actual output in `app/build/config-golden/<case>/`.
 */
class ConfigGeneratorGoldenTest {

    private var previousProfileDir: File? = null
    private var previousProfileLogger: (String, Throwable?) -> Unit = { _, _ -> }
    private var previousRouteDir: File? = null
    private var previousRouteLogger: (String, Throwable?) -> Unit = { _, _ -> }
    private var previousSettingsDir: File? = null
    private var previousSettingsLogger: (String, Throwable?) -> Unit = { _, _ -> }

    @Before
    fun setUp() {
        previousProfileDir = DartProfileStore.directory
        previousProfileLogger = DartProfileStore.logger
        previousRouteDir = RouteJsonStore.directory
        previousRouteLogger = RouteJsonStore.logger
        previousSettingsDir = SettingsJsonStore.directory
        previousSettingsLogger = SettingsJsonStore.logger
        DartProfileStore.logger = { _, _ -> }
        RouteJsonStore.logger = { _, _ -> }
        SettingsJsonStore.logger = { _, _ -> }
    }

    @After
    fun tearDown() {
        DartProfileStore.directory = previousProfileDir
        DartProfileStore.logger = previousProfileLogger
        RouteJsonStore.directory = previousRouteDir
        RouteJsonStore.logger = previousRouteLogger
        SettingsJsonStore.directory = previousSettingsDir
        SettingsJsonStore.logger = previousSettingsLogger
        DartProfileStore.invalidate()
    }

    @Test
    fun `golden fixtures match the kotlin generator byte for byte`() {
        val root = fixtureRoot()
        val cases = root.listFiles { file -> file.isDirectory }?.sortedBy { it.name }.orEmpty()
        assertTrue("no config-golden fixtures under ${root.absolutePath}", cases.isNotEmpty())

        val update = System.getProperty(ConfigGoldenPaths.UPDATE_PROPERTY) == "true"
        val failures = ArrayList<String>()
        for (caseDir in cases) {
            val caseName = caseDir.name
            val generated = try {
                generate(caseDir)
            } catch (error: Throwable) {
                failures.add("$caseName: generator threw ${error::class.java.simpleName}: ${error.message}\n${error.stackTraceToString()}")
                continue
            }
            val actual = generated.coreConfig
            writeActual(caseName, generated)

            if (update) {
                println("config-golden: wrote actual for $caseName")
                continue
            }

            val expectedFile = File(caseDir, EXPECTED)
            if (!expectedFile.isFile) {
                failures.add("$caseName: expected.json is missing; run config_golden.py --update --case $caseName")
                continue
            }
            val expectedDocument = try {
                JSONObject(expectedFile.readText(Charsets.UTF_8))
            } catch (error: Exception) {
                failures.add("$caseName: expected.json is not valid JSON: ${error.message}")
                continue
            }
            if (expectedDocument.optString("generatedBy") != GENERATED_BY) {
                failures.add("$caseName: expected.json was not produced by $GENERATED_BY")
                continue
            }
            val expected = try {
                expectedDocument.getString("coreConfig")
            } catch (error: Exception) {
                failures.add("$caseName: expected.json has no coreConfig string: ${error.message}")
                continue
            }
            // The digest is part of the oracle contract, not an optional extra: a
            // missing one would let a hand-edited coreConfig pass this test.
            val expectedSha = expectedDocument.optString("sha256")
            if (expectedSha.isEmpty() || expectedSha != sha256(expected)) {
                failures.add("$caseName: expected.json sha256 is missing or does not match its coreConfig (edited by hand?)")
                continue
            }
            // An expectError case pins the failure text instead of a config; a successful build
            // must not carry one, so a stale expectation cannot silently pass.
            val expectedError = if (expectedDocument.has("error")) expectedDocument.optString("error") else null
            if (expectedError != generated.error) {
                failures.add(
                    "$caseName: error differs\n  expected: ${expectedError ?: "<none>"}\n  actual:   ${generated.error ?: "<none>"}",
                )
                continue
            }
            if (expected != actual) {
                failures.add("$caseName: ${describeFirstDifference(expected, actual)}")
            }
        }
        if (failures.isNotEmpty()) {
            fail(failures.joinToString("\n\n"))
        }
    }

    /** The production input chain for one fixture: documents -> SettingsMapper -> ConfigGenerator.build. */
    private fun generate(caseDir: File): GeneratedConfig {
        val work = Files.createTempDirectory("config-golden-${caseDir.name}-").toFile()
        try {
            for (name in INPUT_FILES) {
                val source = File(caseDir, name)
                assertTrue("$name is missing in fixture ${caseDir.name}", source.isFile)
                source.copyTo(File(work, name), overwrite = true)
            }
            val buildJson = JSONObject(File(work, BUILD).readText(Charsets.UTF_8))
            val selectedProfileId = buildJson.optLong("selectedProfileId", -1L)
            assertTrue("build.json selectedProfileId must be a profile id", selectedProfileId > 0L)
            // build.json's mode is a case-level override of the settings document's serviceMode,
            // applied to the copied document so DataStore derives mixedInboundDisabled the same way
            // a real start would.
            val mode = buildJson.optString("mode", "")
            if (mode.isNotEmpty()) {
                assertTrue("build.json mode must be \"vpn\" or \"proxy\", not \"$mode\"", mode == "vpn" || mode == "proxy")
                applyServiceMode(work, mode)
            }

            DartProfileStore.directory = work
            DartProfileStore.invalidate()
            RouteJsonStore.directory = work
            SettingsJsonStore.directory = work

            // SettingsMapper generates a random core_box_api_secret when the row is missing/blank;
            // a golden fixture must pin it or every run produces a different config.
            assertTrue(
                "${caseDir.name}: settings.json must set a non-empty core_box_api_secret " +
                    "(otherwise each build generates a random one)",
                !SettingsJsonStore.get("core_box_api_secret").isNullOrEmpty(),
            )
            val clashPort = SettingsJsonStore.get("core_box_clash_api")?.trim()?.toIntOrNull() ?: 0
            if (clashPort > 0) {
                assertTrue(
                    "${caseDir.name}: settings.json enables the Clash API and must set core_box_clash_api_secret",
                    !SettingsJsonStore.get("core_box_clash_api_secret").isNullOrEmpty(),
                )
            }
            // ConfigGenerator.validDuration("") builds its error text from Android resources, which a
            // plain JVM test has no Context for: fixtures must use a syntactically valid non-empty value.
            assertTrue(
                "${caseDir.name}: settings.json must set a non-empty dns_query_timeout (e.g. \"5s\"); " +
                    "the JVM oracle cannot render Validation's Android string for an empty duration",
                !SettingsJsonStore.get("dns_query_timeout").isNullOrEmpty(),
            )
            if (SettingsJsonStore.get("dns_optimistic") == "true") {
                assertTrue(
                    "${caseDir.name}: dns_optimistic requires a non-empty dns_optimistic_timeout for the JVM oracle",
                    !SettingsJsonStore.get("dns_optimistic_timeout").isNullOrEmpty(),
                )
            }

            var settings = SettingsMapper.generatorSettings()
            settings = settings.copy(deferRuleSets = buildJson.optBoolean("deferRuleSets", false))

            // Production routingInput() also carries the srslist catalog and selector store. The
            // fixtures themselves only use URL rule-sets, and an auto-selector reads its groups
            // from that same Dart-owned document, so the store is the production one here too.
            // FlroneMode is part of the same production seam: buildMain rewrites the route profile
            // for the stored outbound mode before the generator sees it.
            val outboundMode = buildJson.optString("outboundMode", "rule")
            assertTrue(
                "build.json outboundMode must be one of ${FlroneMode.modes}, not \"$outboundMode\"",
                outboundMode in FlroneMode.modes,
            )
            val routing = FlroneMode.rewrite(
                RoutingInput(
                    RouteManager.current(),
                    RuleSetCatalog(emptyList()),
                    SettingsMapper.selectorStore(),
                ),
                FlroneMode.Mode.of(outboundMode),
            )
            // A selector plan reads the clock for result freshness and warm-health ages; a fixture
            // that pins such inputs also pins the clock, so the oracle output is reproducible.
            val clockUnixSeconds = if (buildJson.has("clockUnixSeconds")) {
                buildJson.optLong("clockUnixSeconds", 0L)
            } else {
                null
            }
            val generator = ConfigGenerator(
                ProfileProvider { id -> DartProfileStore.profile(id)?.outbound },
                settings,
                SettingsMapper.buildContext(),
                routing,
                clock = if (clockUnixSeconds != null) {
                    ({ clockUnixSeconds })
                } else {
                    ({ System.currentTimeMillis() / 1000 })
                },
            )
            val generated = generator.build(
                selectedProfileId,
                buildJson.optLong("landingProxyId", -1L),
                buildJson.optLong("frontProxyId", -1L),
                buildJson.optString("groupName", ""),
            )
            val expectError = buildJson.optBoolean("expectError", false)
            if (expectError) {
                assertTrue(
                    "${caseDir.name}: build.json sets expectError, but the generator succeeded",
                    !generated.ok,
                )
                assertTrue(
                    "${caseDir.name}: an expectError build must not return a coreConfig",
                    generated.coreConfig.isEmpty(),
                )
            } else {
                assertTrue("${caseDir.name}: ${generated.error ?: "empty config"}", generated.ok)
                assertTrue("${caseDir.name}: the generator returned an empty config", generated.coreConfig.isNotEmpty())
            }
            return generated
        } finally {
            DartProfileStore.directory = null
            RouteJsonStore.directory = null
            SettingsJsonStore.directory = null
            work.deleteRecursively()
        }
    }

    /** Rewrites `serviceMode` in the copied settings document (build.json's case-level mode override). */
    private fun applyServiceMode(dir: File, mode: String) {
        val document = JSONObject(File(dir, "settings.json").readText(Charsets.UTF_8))
        val rows = document.optJSONArray("rows") ?: error("settings.json has no rows array")
        var found = false
        for (index in 0 until rows.length()) {
            val row = rows.optJSONObject(index) ?: continue
            if (row.optString("key") == "serviceMode") {
                row.put("value", mode)
                found = true
            }
        }
        if (!found) rows.put(JSONObject().put("key", "serviceMode").put("value", mode))
        File(dir, "settings.json").writeText(document.toString(), Charsets.UTF_8)
    }

    /** This test's own output directory; `config_golden.py` reads it and is the only writer of expected.json. */
    private fun writeActual(caseName: String, generated: GeneratedConfig) {
        val dir = File(ConfigGoldenPaths.outputRoot(), caseName).apply { mkdirs() }
        File(dir, "actual.json").writeText(expectedDocument(generated), Charsets.UTF_8)
    }

    private fun expectedDocument(generated: GeneratedConfig): String = buildString {
        append("{\n")
        append("  \"version\": 1,\n")
        append("  \"generatedBy\": \"").append(GENERATED_BY).append("\",\n")
        append("  \"sha256\": \"").append(sha256(generated.coreConfig)).append("\",\n")
        append("  \"coreConfig\": ").append(JSONObject.quote(generated.coreConfig))
        // An expectError case pins the failure text; a successful build has no error key.
        generated.error?.let { append(",\n  \"error\": ").append(JSONObject.quote(it)) }
        append('\n')
        append("}\n")
    }

    private fun fixtureRoot(): File {
        val url = javaClass.getResource("/config-golden")
            ?: error("missing test resources /config-golden")
        return File(url.toURI())
    }

    private fun describeFirstDifference(expected: String, actual: String): String {
        val left = expected.toByteArray(Charsets.UTF_8)
        val right = actual.toByteArray(Charsets.UTF_8)
        val shared = minOf(left.size, right.size)
        var offset = 0
        while (offset < shared && left[offset] == right[offset]) offset++
        val leftContext = String(left, maxOf(0, offset - 24), minOf(left.size, offset + 24) - maxOf(0, offset - 24), Charsets.UTF_8)
        val rightContext = String(right, maxOf(0, offset - 24), minOf(right.size, offset + 24) - maxOf(0, offset - 24), Charsets.UTF_8)
        return buildString {
            append("coreConfig differs at byte offset ").append(offset)
            append(" (expected ").append(left.size).append(" bytes, actual ").append(right.size).append(" bytes)\n")
            append("  expected[..]: ").append(leftContext.replace("\n", "\\n")).append('\n')
            append("  actual[..]:   ").append(rightContext.replace("\n", "\\n"))
        }
    }

    private companion object {
        const val EXPECTED = "expected.json"
        const val BUILD = "build.json"
        const val GENERATED_BY = "ConfigGeneratorGoldenTest"
        val INPUT_FILES = listOf("profiles.json", "settings.json", "global_route_rules.json", BUILD)

        fun sha256(text: String): String =
            MessageDigest.getInstance("SHA-256").digest(text.toByteArray(Charsets.UTF_8))
                .joinToString("") { String.format(Locale.ROOT, "%02x", it) }
    }
}

/** Path resolution shared with tools/diagnostics/config_golden.py. */
internal object ConfigGoldenPaths {
    const val UPDATE_PROPERTY = "config.golden.update"
    const val OUTPUT_PROPERTY = "config.golden.outputDir"

    /** Defaults to `app/build/config-golden` because Gradle runs unit tests from the app module. */
    fun outputRoot(): File =
        System.getProperty(OUTPUT_PROPERTY)?.takeIf { it.isNotBlank() }?.let(::File)
            ?: File("build/config-golden")
}
