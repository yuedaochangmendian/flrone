bool isZh(BuildContext context) =>
    Localizations.localeOf(context).languageCode.toLowerCase() == 'zh';

String translate(BuildContext context, String text) =>
    isZh(context) ? (_zh[text] ?? text) : text;

extension TranslateContext on BuildContext {
  String tr(String text) => translate(this, text);
}
